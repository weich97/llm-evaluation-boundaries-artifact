"""Public artifact integrity and print-size figure regression checks."""
from __future__ import annotations

import hashlib
import importlib
import json

import pytest
import verify_tmlr_supplement as verifier


@pytest.mark.parametrize("mutation", [None, "missing", "changed", "extra", "nested_git"])
def test_manifest_is_fail_closed(tmp_path, monkeypatch, mutation):
    monkeypatch.setattr(verifier, "REPRODUCED", ("input.txt",))
    source = tmp_path / "input.txt"
    source.write_bytes(b"frozen input\n")
    manifest = {"schema_version": "tmlr.ab.artifact.v2", "reproduced": ["input.txt"],
                "files": {"input.txt": hashlib.sha256(source.read_bytes()).hexdigest()}}
    (tmp_path / "artifact_manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    (tmp_path / ".git").mkdir()
    (tmp_path / ".git/config").write_text("local metadata", encoding="utf-8")
    if mutation == "missing":
        source.unlink()
    elif mutation == "changed":
        source.write_bytes(b"changed")
    elif mutation == "extra":
        (tmp_path / "extra.txt").touch()
    elif mutation == "nested_git":
        (tmp_path / "nested/.git").mkdir(parents=True)
        (tmp_path / "nested/.git/extra.txt").touch()
    if mutation:
        with pytest.raises(ValueError):
            verifier.verify_manifest(tmp_path)
    else:
        verifier.verify_manifest(tmp_path)


@pytest.mark.parametrize("name", ["render_studyA_figures", "render_finaudit_figures", "render_pooling_figures"])
def test_figures_keep_print_size_fonts(name, tmp_path, monkeypatch):
    import matplotlib as mpl
    from matplotlib.text import Text

    renderer = importlib.import_module(name)
    monkeypatch.setattr(renderer, "ROOT", tmp_path)
    monkeypatch.setattr(renderer, "OUT_DIR", tmp_path / "figures")
    saves = []

    def inspect(figure, *args, **kwargs):
        figure.canvas.draw()
        assert figure.get_figwidth() == pytest.approx(6.5)
        assert len(figure.axes) == 2
        assert figure.axes[0].get_position().y0 > figure.axes[1].get_position().y1
        assert all(text.get_fontsize() >= 9 for text in figure.findobj(Text)
                   if text.get_visible() and text.get_text().strip())
        assert not figure.texts  # No restored figure-bottom prose notes.
        assert kwargs.get("bbox_inches") != "tight"
        assert mpl.rcParams["font.serif"] == ["STIXGeneral"]
        assert mpl.rcParams["pdf.fonttype"] == 42
        saves.append(args[0])

    monkeypatch.setattr(renderer.plt.Figure, "savefig", inspect)
    with mpl.rc_context():
        assert renderer.main() == 0
    assert len(saves) == 2


