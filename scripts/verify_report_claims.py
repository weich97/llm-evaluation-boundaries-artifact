"""Manuscript-side layer over the released-results gate.

The data checks live in ``verify_released_results.py``, which ships in the
supplement. That file answers "does the released artifact still say what the
analysis computes". This file adds the manuscript-side question: does
``paper/tech_report/main.tex`` still print those values, and which claims can no
assertion cover at all?

The split exists so the data checks have exactly one implementation. A second
copy carrying the same arithmetic would drift, which is the failure this whole
apparatus was built to catch.

Usage:
    python scripts/verify_report_claims.py            # data checks + paper side
    python scripts/verify_report_claims.py --study B  # one study
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import verify_released_results as released

PAPER = ROOT / "paper/tech_report/main.tex"

#: Claims the report makes that no assertion can cover, with why. Anything here
#: is a place the report must stay hedged, because nothing will catch drift.
UNASSERTABLE: list[tuple[str, str]] = [
    (
        "plan predates collection",
        "the digest chain proves plan/corpus agreement, not precedence in time; "
        "no third-party timestamp exists, so ordering cannot be asserted here",
    ),
]

#: For each data check, the fragments the manuscript must still print. The data
#: side is already verified by the imported module; this is only the "and the
#: paper still says so" half.
PAPER_MUST_PRINT: dict[str, list[str]] = {
    "execution decomposition": ["$-0.0170$", "$+0.0035$", "$-0.0135$"],
    "ranking stability table": [
        "0.7635", "0.2608", "0.5368", "0.5678", "0.7369", "0.3265",
    ],
    "inactive row inflates tau_b": ["$358$ of $360$"],
    "frozen grid and decision rule": [
        "$600/600$", "median is $0.267$", "three cells survive Holm correction",
    ],
    "frozen cardinality split": ["$70$--$88\\%$", "$0$--$48\\%$"],
    "specificity and exact sets": [
        "$98/100$", "$45/100$", "0.149", "0.199",
        "$29/300$", "$108/300$", "$21/100$", "$7/100$",
    ],
}

# These phrases belonged to results that the implementation audit invalidated.
# Their reappearance is a failure even if every remaining number still matches.
PAPER_MUST_NOT_PRINT: tuple[str, ...] = (
    "$12$ variants do not escape",
    "the two least-catching layers are exactly the irreplaceable ones",
    "cryptographically authenticated gate",
    "For a deterministic agent this does not arise",
    "one-answer behaviour is compliance, not bias",
    "chooses the benign reading",
    "will be credited with catching whatever is there",
)


def _paper_text() -> str:
    if not PAPER.exists():
        return ""
    return "\n".join(
        line
        for line in PAPER.read_text(encoding="utf-8").splitlines()
        if not line.strip().startswith("%")
    )


def _normalize(value: str) -> str:
    return re.sub(r"\s+", " ", value)


def _paper_contains(fragment: str, text: str) -> bool:
    return _normalize(fragment) in _normalize(text)


def _appendix_is_current() -> tuple[bool, str]:
    """Whether the generated appendix fragment still matches the data.

    The appendix is emitted by ``build_appendix_tables.py``. If someone
    regenerates an analysis and forgets to re-emit it, the appendix silently
    disagrees with the body -- the precise failure this apparatus exists to
    catch, arriving through the one file nobody re-reads.
    """

    fragment = ROOT / "paper/tech_report/appendix_tables.tex"
    if not fragment.exists():
        return False, "appendix_tables.tex has not been generated"

    import build_appendix_tables as appendix

    expected = "\n\n".join(
        [
            "% Generated by scripts/build_appendix_tables.py -- do not edit by hand.",
            appendix.study_a_table(),
            appendix.study_b_table(),
        ]
    ) + "\n"
    actual = fragment.read_text(encoding="utf-8")
    if _normalize(actual) != _normalize(expected):
        return False, "appendix_tables.tex is stale; re-run scripts/build_appendix_tables.py"
    return True, f"appendix matches the data ({len(actual.splitlines())} lines)"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Verify the report's load-bearing claims.")
    parser.add_argument("--study", choices=["A", "B"], help="run one study's checks only")
    parser.add_argument("--strict", action="store_true", help="Require every released data input")
    parser.add_argument("--require-manuscript", action="store_true",
                        help="Fail when paper/tech_report/main.tex is absent (local manuscript checkouts)")
    args = parser.parse_args(argv)

    forwarded = ["--study", args.study] if args.study else []
    if args.strict:
        forwarded.append("--strict")
    status = released.main(forwarded)

    if not PAPER.exists():
        print(f"\n{PAPER.relative_to(ROOT)} is not in this checkout; the paper-side half was not run.")
        return 1 if args.require_manuscript else status

    text = _paper_text()
    selected = {name for study, name, _ in released.CHECKS if args.study is None or study == args.study}
    missing: list[str] = []
    checked = 0
    for name, fragments in PAPER_MUST_PRINT.items():
        if name not in selected:
            continue
        for fragment in fragments:
            checked += 1
            if not _paper_contains(fragment, text):
                missing.append(f"{name}: {fragment}")

    forbidden = [fragment for fragment in PAPER_MUST_NOT_PRINT if _paper_contains(fragment, text)]

    print()
    if missing:
        print(f"{len(missing)} of {checked} paper-side assertions FAILED:")
        for entry in missing:
            print(f"  - the report no longer prints {entry}")
        status = 1
    else:
        print(f"{checked}/{checked} paper-side assertions verified against {PAPER.name}")

    if forbidden:
        print(f"{len(forbidden)} withdrawn claim(s) reappeared:")
        for fragment in forbidden:
            print(f"  - {fragment}")
        status = 1

    current, detail = _appendix_is_current()
    print(f"appendix: {'ok' if current else 'STALE'} -- {detail}")
    if not current:
        status = 1

    print("\nClaims with no executable assertion (the report must stay hedged here):")
    for claim, reason in UNASSERTABLE:
        print(f"  - {claim}: {reason}")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
